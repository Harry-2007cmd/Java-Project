#!/usr/bin/env python3
"""
Generates src/main/resources/db/demo_data.sql - a believable month of parking history plus
a snapshot of "right now" so the admin dashboard charts and the 3D map look alive.
Deterministic (fixed seed), additive and safe to re-run: it only touches rows it created
(vehicles whose owner_contact is 'DEMO') and never touches real users or real vehicles.

    python3 tools/gen_demo_data.py > src/main/resources/db/demo_data.sql
"""
import datetime, math, random

random.seed(2024)

ZONES = [  # (prefix, type, location, count)  - zone names follow Chitkara University's public parking areas
    ("T", "CAR",  "Turing Block Parking",  12),
    ("G", "CAR",  "Gate 3 Parking",        10),
    ("P", "CAR",  "Picasso Block (Rear)",   8),
    ("W", "BIKE", "Two-Wheeler Parking",   16),
    ("S", "BUS",  "Bus Bay",                6),
    ("E", "EV",   "EV Charging Zone",       6),
]
RATE = {"CAR": 20, "BIKE": 10, "BUS": 50, "EV": 15}
slots = {}
for pre, typ, loc, n in ZONES:
    slots[typ] = slots.get(typ, [])
    for i in range(1, n + 1):
        slots[typ].append((f"{pre}-{i:02d}", loc))

FIRST = ["Aarav","Vivaan","Aditya","Arjun","Rohan","Ishaan","Kabir","Dev","Karan","Manav","Harsh","Nikhil",
         "Simran","Priya","Ananya","Diya","Kavya","Riya","Neha","Pooja","Tanvi","Meera","Jasleen","Harleen",
         "Gurpreet","Manpreet","Navdeep","Amandeep","Sukhdeep","Rajveer"]
LAST = ["Sharma","Singh","Verma","Gill","Kaur","Mehta","Bansal","Garg","Arora","Chopra","Sandhu","Bedi",
        "Thakur","Kapoor","Malhotra","Joshi","Dhillon","Grewal","Sethi","Walia"]
LETTERS = "ABCDEFGHJKLMNPRSTUVWXYZ"

def plate(i):
    return f"PB{random.choice(['10','65','11','12'])}{random.choice(LETTERS)}{random.choice(LETTERS)}{1000 + i * 7 % 9000}"

POOL = {"CAR": 40, "BIKE": 50, "EV": 10, "BUS": 6}
vehicles = {}
n = 0
seen = set()
for typ, count in POOL.items():
    vehicles[typ] = []
    for _ in range(count):
        n += 1
        p = plate(n)
        while p in seen:
            n += 1; p = plate(n)
        seen.add(p)
        owner = f"{random.choice(FIRST)} {random.choice(LAST)}" if typ != "BUS" else f"Campus Transport {len(vehicles[typ]) + 1}"
        vehicles[typ].append((p, owner))

def fee(typ, minutes):
    return RATE[typ] * max(1, math.ceil(minutes / 60))

out = []
w = out.append
w("-- Demo data for the admin dashboard (generated by tools/gen_demo_data.py - do not edit by hand).")
w("-- Additive and re-runnable: it only replaces rows it created itself (vehicles with owner_contact = 'DEMO').")
w("USE campus_parking;")
w("-- MySQL Workbench starts in 'safe update' mode (error 1175); switch it off for this script only.")
w("SET @old_safe := @@SQL_SAFE_UPDATES;")
w("SET SQL_SAFE_UPDATES = 0;")
w("")
w("-- 0. Make sure the maintenance column exists (no-op if it already does).")
w("SET @has := (SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'parking_slots' AND COLUMN_NAME = 'out_of_service');")
w("SET @ddl := IF(@has = 0, 'ALTER TABLE parking_slots ADD COLUMN out_of_service BOOLEAN NOT NULL DEFAULT FALSE', 'SELECT 1');")
w("PREPARE stmt FROM @ddl; EXECUTE stmt; DEALLOCATE PREPARE stmt;")
w("")
w("-- 1. Remove any earlier demo data.")
w("DELETE FROM parking_records WHERE vehicle_id IN (SELECT vehicle_id FROM vehicles WHERE owner_contact = 'DEMO');")
w("DELETE FROM vehicles WHERE owner_contact = 'DEMO';")
w("UPDATE parking_slots SET is_occupied = FALSE WHERE slot_id NOT IN (SELECT slot_id FROM parking_records WHERE exit_time IS NULL);")
w("")
w("-- 2. The campus slot layout (existing slots are left alone).")
w("INSERT IGNORE INTO parking_slots (slot_number, vehicle_type, location, is_occupied) VALUES")
rows = []
for pre, typ, loc, cnt in ZONES:
    for i in range(1, cnt + 1):
        rows.append(f"('{pre}-{i:02d}', '{typ}', '{loc}', FALSE)")
w(",\n".join(rows) + ";")
w("")
w("-- 3. Demo vehicles.")
w("INSERT INTO vehicles (vehicle_number, vehicle_type, owner_name, owner_contact) VALUES")
rows = []
for typ, lst in vehicles.items():
    for p, owner in lst:
        rows.append(f"('{p}', '{typ}', '{owner}', 'DEMO')")
w(",\n".join(rows) + ";")
w("")

def insert(plate_, slot, entry_sql, exit_sql, minutes, fee_amt):
    ex = exit_sql if exit_sql else "NULL"
    d = minutes if minutes is not None else "NULL"
    f = fee_amt if fee_amt is not None else "NULL"
    w("INSERT INTO parking_records (vehicle_id, slot_id, entry_time, exit_time, duration_minutes, fee_amount) "
      f"SELECT v.vehicle_id, s.slot_id, {entry_sql}, {ex}, {d}, {f} FROM vehicles v, parking_slots s "
      f"WHERE v.vehicle_number = '{plate_}' AND s.slot_number = '{slot}';")

w("-- 4. Thirty days of finished sessions (morning rush, lunch bump, quieter weekends).")
HOUR_W = {7: 4, 8: 14, 9: 16, 10: 8, 11: 5, 12: 6, 13: 8, 14: 5, 15: 3, 16: 2}
hours = list(HOUR_W); weights = [HOUR_W[h] for h in hours]
MIX = ["BIKE"] * 46 + ["CAR"] * 40 + ["EV"] * 9 + ["BUS"] * 5
for d in range(30, 0, -1):
    # The SQL uses dates relative to the day it is loaded; the weekday rhythm is aligned to the day this
    # script runs, so re-generate the file if you load it long after generating it.
    dow = (datetime.date.today() - datetime.timedelta(days=d)).weekday()   # 0 = Monday
    sessions = {5: 20, 6: 12}.get(dow, random.randint(38, 48))
    for _ in range(sessions):
        typ = random.choice(MIX)
        p, _o = random.choice(vehicles[typ])
        slot, _l = random.choice(slots[typ])
        h = random.choices(hours, weights)[0]
        mi = random.randint(0, 59)
        minutes = random.choice([random.randint(45, 150), random.randint(180, 330), random.randint(300, 540)]) if typ != "BUS" else random.randint(240, 420)
        entry = f"DATE_SUB(CURDATE(), INTERVAL {d} DAY) + INTERVAL {h * 60 + mi} MINUTE"
        exit_ = f"DATE_SUB(CURDATE(), INTERVAL {d} DAY) + INTERVAL {h * 60 + mi + minutes} MINUTE"
        insert(p, slot, entry, exit_, minutes, fee(typ, minutes))

w("")
w("-- 5. Sessions that already ended earlier today (so 'today's revenue' is not zero).")
for k in range(9):
    typ = random.choice(["BIKE", "BIKE", "CAR", "CAR", "EV"])
    p, _o = random.choice(vehicles[typ]); slot, _l = random.choice(slots[typ])
    minutes = random.randint(50, 170)
    ago = random.randint(5, 90)
    insert(p, slot, f"NOW() - INTERVAL {ago + minutes} MINUTE", f"NOW() - INTERVAL {ago} MINUTE", minutes, fee(typ, minutes))

w("")
w("-- 6. Vehicles parked right now. Gate 3 is nearly full and three vehicles are overstaying.")
CURRENT = {   # slot -> minutes parked so far
    # Gate 3: 9 of 10 (90%)
    **{f"G-{i:02d}": random.randint(25, 400) for i in range(1, 10)},
    # Turing: 7 of 11 usable (T-12 is under maintenance)
    **{f"T-{i:02d}": random.randint(30, 380) for i in range(1, 8)},
    # Picasso rear: 3 of 8
    **{f"P-{i:02d}": random.randint(20, 300) for i in range(1, 4)},
    # Two-wheelers: 12 of 16
    **{f"W-{i:02d}": random.randint(15, 420) for i in range(1, 13)},
    # Buses: 4 of 6
    **{f"S-{i:02d}": random.randint(60, 400) for i in range(1, 5)},
    # EV: 3 of 5 usable (E-06 under maintenance)
    **{f"E-{i:02d}": random.randint(40, 300) for i in range(1, 4)},
}
CURRENT["G-03"] = 11 * 60 + 20      # overstays
CURRENT["W-05"] = 9 * 60 + 35
CURRENT["T-02"] = 10 * 60 + 5
type_of = {s: t for t, lst in slots.items() for s, _ in lst}
used = set()
for slot, minutes in CURRENT.items():
    typ = type_of[slot]
    p, _o = next((v for v in vehicles[typ] if v[0] not in used), vehicles[typ][0])
    used.add(p)
    insert(p, slot, f"NOW() - INTERVAL {minutes} MINUTE", None, None, None)
w("")
w("UPDATE parking_slots SET is_occupied = TRUE WHERE slot_id IN (SELECT slot_id FROM parking_records WHERE exit_time IS NULL);")
w("")
w("-- 7. Two slots closed for maintenance (only free slots can be closed).")
w("UPDATE parking_slots SET out_of_service = TRUE WHERE slot_number IN ('T-12', 'E-06') AND is_occupied = FALSE;")
w("")
w("SET SQL_SAFE_UPDATES = @old_safe;")
print("\n".join(out))
